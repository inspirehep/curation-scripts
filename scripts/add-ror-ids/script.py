class AddRorIds(SearchCheckDo):
    search_class = InstitutionsSearch

    query = f"addresses.country_code:IN -{ELEMENT}.schema:{SCHEMA}"

    @staticmethod
    def check(record, logger, state):
        if any(id_["schema"] == SCHEMA for id_ in record.get(ELEMENT, [])):
            return False

        ror_id = ROR_IDS.get(record.get("control_number"))
        if ror_id:
            state["ror_id"] = ror_id
            return True

        return False

    @staticmethod
    def do(record, logger, state):
        record.setdefault(ELEMENT, []).append(
            {
                "value": state["ror_id"],
                "schema": SCHEMA,
            }
        )


